const FALLBACK_GLYPH = GLYPHS['?']!;

export function measureBitmapText(text: string, scale = 1): number {
  if (!text) return 0;
  const s = Math.max(1, Math.round(scale));
  let maxLen = 0;
  let curLen = 0;
  for (let i = 0; i < text.length; i++) {
    if (text.charCodeAt(i) === 10) {
      if (curLen > maxLen) maxLen = curLen;
      curLen = 0;
    } else {
      curLen++;
    }
  }
  if (curLen > maxLen) maxLen = curLen;
  if (maxLen === 0) return 0;
  return (maxLen * GLYPH_ADVANCE - 1) * s;
}

function drawSingleLine(
  ctx: CanvasRenderingContext2D,
  line: string,
  x: number,
  y: number,
  scale: number,
  align: 'left' | 'center' | 'right',
): void {
  if (!line) return;
  const lineW = (line.length * GLYPH_ADVANCE - 1) * scale;
  let penX = Math.round(x);
  if (align === 'center') {
    penX = Math.round(x - lineW * 0.5);
  } else if (align === 'right') {
    penX = Math.round(x - lineW);
  }
  const baseY = Math.round(y);

  for (let i = 0; i < line.length; i++) {
    const ch = line.charAt(i).toUpperCase();
    const rows = GLYPHS[ch] ?? FALLBACK_GLYPH;
    for (let r = 0; r < GLYPH_H; r++) {
      const bits = rows[r] ?? 0;
      if (bits === 0) continue;
      let c = 0;
      while (c < GLYPH_W) {
        if ((bits & (1 << (4 - c))) !== 0) {
          let run = 1;
          while (c + run < GLYPH_W && (bits & (1 << (4 - (c + run)))) !== 0) {
            run++;
          }
          ctx.fillRect(penX + c * scale, baseY + r * scale, run * scale, scale);
          c += run;
        } else {
          c++;
        }
      }
    }
    penX += GLYPH_ADVANCE * scale;
  }
}

export function drawBitmapText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
  align: 'left' | 'center' | 'right' = 'left',
): void {
  if (!text) return;
  const s = Math.max(1, Math.round(scale));
  ctx.fillStyle = color;

  if (!text.includes('\n')) {
    drawSingleLine(ctx, text, x, y, s, align);
    return;
  }

  const lines = text.split('\n');
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i] ?? '';
    drawSingleLine(ctx, line, x, y + i * LINE_HEIGHT * s, s, align);
  }
}

export function drawBitmapTextOutlined(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  outlineColor = '#000000',
  scale = 1,
  align: 'left' | 'center' | 'right' = 'left',
): void {
  if (!text) return;
  const s = Math.max(1, Math.round(scale));
  const bx = Math.round(x);
  const by = Math.round(y);
  ctx.fillStyle = outlineColor;
  drawSingleLineOffset(ctx, text, bx - s, by, s, align);
  drawSingleLineOffset(ctx, text, bx + s, by, s, align);
  drawSingleLineOffset(ctx, text, bx, by - s, s, align);
  drawSingleLineOffset(ctx, text, bx, by + s, s, align);
  drawBitmapText(ctx, text, bx, by, color, s, align);
}

function drawSingleLineOffset(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  scale: number,
  align: 'left' | 'center' | 'right',
): void {
  if (!text.includes('\n')) {
    drawSingleLine(ctx, text, x, y, scale, align);
    return;
  }
  const lines = text.split('\n');
  for (let i = 0; i < lines.length; i++) {
    drawSingleLine(ctx, lines[i] ?? '', x, y + i * LINE_HEIGHT * scale, scale, align);
  }
}
